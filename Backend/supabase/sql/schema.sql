-- On signup: create profile automatically
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  meta_name text;
  email_local_part text;
  safe_display_name text;
  free_status_id smallint;
begin
  meta_name := nullif(trim(coalesce(new.raw_user_meta_data->>'display_name', '')), '');
  email_local_part := nullif(trim(split_part(coalesce(new.email, ''), '@', 1)), '');
  safe_display_name := left(coalesce(meta_name, email_local_part, 'Utilisateur'), 80);

  if char_length(safe_display_name) < 2 then
    safe_display_name := 'Utilisateur';
  end if;

  select id
  into free_status_id
  from public.subscription_statuses
  where code = 'free'
  limit 1;

  if free_status_id is null then
    insert into public.subscription_statuses (id, code, label)
    values (1, 'free', 'Free')
    on conflict (code) do update
      set label = excluded.label
    returning id into free_status_id;
  end if;

  if free_status_id is null then
    select id
    into free_status_id
    from public.subscription_statuses
    where code = 'free'
    limit 1;
  end if;

  if new.email is null or trim(new.email) = '' then
    raise warning 'handle_new_user: missing email for auth user %', new.id;
    return new;
  end if;

  if free_status_id is null then
    raise warning 'handle_new_user: missing free subscription status for auth user %', new.id;
    return new;
  end if;

  begin
    insert into public.user_profiles (id, display_name, email, status, status_id)
    values (
      new.id,
      safe_display_name,
      new.email,
      'free',
      free_status_id
    )
    on conflict (id) do update
      set email = excluded.email,
          status_id = coalesce(public.user_profiles.status_id, excluded.status_id);
  exception
    when others then
      raise warning 'handle_new_user failed for auth user %: %', new.id, sqlerrm;
  end;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();

