-- 1) User profile (auth.users keeps email+password)
-- =========================================================
create table if not exists public.subscription_statuses (
  id smallint generated by default as identity primary key,
  code text not null unique check (code in ('free', 'paid_monthly', 'paid_lifetime')),
  label text not null
);

do $$
declare
  max_status_id smallint;
begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'subscription_statuses'
      and column_name = 'id'
      and (
        is_identity = 'YES'
        or column_default is not null
      )
  ) then
    create sequence if not exists public.subscription_statuses_id_seq as smallint;

    select coalesce(max(id), 0)::smallint
    into max_status_id
    from public.subscription_statuses;

    perform setval(
      'public.subscription_statuses_id_seq',
      greatest(max_status_id, 1),
      max_status_id > 0
    );

    alter sequence public.subscription_statuses_id_seq
      owned by public.subscription_statuses.id;

    alter table public.subscription_statuses
      alter column id set default nextval('public.subscription_statuses_id_seq');
  end if;
end $$;

insert into public.subscription_statuses (id, code, label)
values
  (1, 'free', 'Free'),
  (2, 'paid_monthly', 'Paid Monthly'),
  (3, 'paid_lifetime', 'Paid Lifetime')
on conflict (code) do update
set label = excluded.label;

create table if not exists public.user_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(trim(display_name)) between 2 and 80),
  email text not null,
  status text not null default 'free' check (status in ('free', 'paid_monthly', 'paid_lifetime')),
  status_id smallint not null references public.subscription_statuses(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.user_profiles
  add column if not exists status_id smallint;

alter table public.user_profiles
  drop constraint if exists user_profiles_status_check;

alter table public.user_profiles
  add constraint user_profiles_status_check
  check (status in ('free', 'paid_monthly', 'paid_lifetime', 'premium'));

update public.user_profiles up
set status_id = case
  when lower(up.status) = 'free' then 1
  when lower(up.status) = 'paid_monthly' then 2
  when lower(up.status) in ('paid_lifetime', 'premium') then 3
  else up.status_id
end
where up.status_id is null
  and lower(up.status) in ('free', 'paid_monthly', 'paid_lifetime', 'premium');

update public.user_profiles up
set status_id = 1
where up.status_id is null
;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'user_profiles_status_id_fkey'
  ) then
    alter table public.user_profiles
      add constraint user_profiles_status_id_fkey
      foreign key (status_id) references public.subscription_statuses(id);
  end if;
end $$;

alter table public.user_profiles
  alter column status_id set not null;

