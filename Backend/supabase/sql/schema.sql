create or replace function public.history_retention_days_for_profile(
  profile_status text,
  profile_status_id smallint default null
)
returns integer
language sql
immutable
as $$
  select case
    when coalesce(profile_status_id in (2, 3), false)
      or lower(coalesce(profile_status, '')) in ('paid', 'premium', 'paid_monthly', 'paid_lifetime')
    then 90
    else 7
  end;
$$;

create or replace function public.history_retention_days_for_user(target_user_id uuid)
returns integer
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce(
    (
      select public.history_retention_days_for_profile(up.status, up.status_id)
      from public.user_profiles up
      where up.id = target_user_id
      limit 1
    ),
    7
  );
$$;

grant execute on function public.history_retention_days_for_user(uuid) to authenticated, service_role;

create or replace function public.purge_expired_parking_sessions(target_user_id uuid default null)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  deleted_count integer;
begin
  with deleted_rows as (
    delete from public.parking_sessions ps
    where (target_user_id is null or ps.user_id = target_user_id)
      and ps.end_time is not null
      and ps.start_time < now() - make_interval(days => public.history_retention_days_for_user(ps.user_id))
    returning 1
  )
  select count(*)
  into deleted_count
  from deleted_rows;

  return coalesce(deleted_count, 0);
end;
$$;

grant execute on function public.purge_expired_parking_sessions(uuid) to service_role;

create or replace function public.enforce_parking_session_retention()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.purge_expired_parking_sessions(new.user_id);
  return new;
end;
$$;

